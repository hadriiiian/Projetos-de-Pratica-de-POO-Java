public class Paciente {
	private float peso;
	private float altura;
	
	//getters
	
	public float getPeso() {
		return peso;
	}
	public float getAltura() {
		return altura;
	}
	
	//setters
	
	public void setPeso(float newValue) {
		peso = newValue;
	}
	public void setAltura(float newValue) {
		altura = newValue;
	}
}
